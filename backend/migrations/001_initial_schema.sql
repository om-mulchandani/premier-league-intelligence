CREATE TABLE IF NOT EXISTS seasons (
    season_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id BIGINT NOT NULL REFERENCES competitions (competition_id),
    season_code TEXT NOT NULL,
    start_year SMALLINT NOT NULL,
    end_year SMALLINT NOT NULL,
    CONSTRAINT seasons_competition_code_unique UNIQUE (competition_id, season_code),
    CONSTRAINT seasons_year_range_valid CHECK (end_year = start_year + 1),
    CONSTRAINT seasons_code_format_valid CHECK (
        season_code = start_year::TEXT || '-' || RIGHT(end_year::TEXT, 2)
    )
);

CREATE TABLE IF NOT EXISTS teams (
    team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name TEXT NOT NULL,
    normalized_name TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT teams_names_not_blank CHECK (
        LENGTH(BTRIM(canonical_name)) > 0 AND LENGTH(BTRIM(normalized_name)) > 0
    )
);

CREATE TABLE IF NOT EXISTS data_sources (
    data_source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL,
    source_file TEXT NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    retrieved_at TIMESTAMPTZ,
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT data_sources_provider_hash_unique UNIQUE (provider, source_sha256),
    CONSTRAINT data_sources_sha256_valid CHECK (source_sha256 ~ '^[0-9a-f]{64}$')
);

CREATE TABLE IF NOT EXISTS ingestion_runs (
    ingestion_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_source_id BIGINT NOT NULL REFERENCES data_sources (data_source_id),
    schema_version TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'running',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    records_seen INTEGER NOT NULL DEFAULT 0,
    records_loaded INTEGER NOT NULL DEFAULT 0,
    error_message TEXT,
    CONSTRAINT ingestion_runs_status_valid CHECK (
        status IN ('running', 'succeeded', 'failed')
    ),
    CONSTRAINT ingestion_runs_counts_nonnegative CHECK (
        records_seen >= 0 AND records_loaded >= 0 AND records_loaded <= records_seen
    ),
    CONSTRAINT ingestion_runs_completion_valid CHECK (
        (status = 'running' AND completed_at IS NULL)
        OR (status IN ('succeeded', 'failed') AND completed_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS matches (
    match_id CHAR(64) PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES seasons (season_id),
    match_date DATE NOT NULL,
    home_team_id BIGINT NOT NULL REFERENCES teams (team_id),
    away_team_id BIGINT NOT NULL REFERENCES teams (team_id),
    home_goals SMALLINT NOT NULL,
    away_goals SMALLINT NOT NULL,
    result CHAR(1) NOT NULL,
    CONSTRAINT matches_id_sha256_valid CHECK (match_id ~ '^[0-9a-f]{64}$'),
    CONSTRAINT matches_teams_distinct CHECK (home_team_id <> away_team_id),
    CONSTRAINT matches_goals_nonnegative CHECK (home_goals >= 0 AND away_goals >= 0),
    CONSTRAINT matches_result_valid CHECK (
        result = CASE
            WHEN home_goals > away_goals THEN 'H'
            WHEN home_goals < away_goals THEN 'A'
            ELSE 'D'
        END
    ),
    CONSTRAINT matches_fixture_unique UNIQUE (
        season_id, match_date, home_team_id, away_team_id
    )
);

CREATE TABLE IF NOT EXISTS match_provenance (
    match_provenance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id CHAR(64) NOT NULL REFERENCES matches (match_id) ON DELETE CASCADE,
    ingestion_run_id BIGINT NOT NULL REFERENCES ingestion_runs (ingestion_run_id),
    source_record INTEGER NOT NULL,
    raw_record JSONB NOT NULL DEFAULT '{}'::JSONB,
    CONSTRAINT match_provenance_source_record_positive CHECK (source_record > 0),
    CONSTRAINT match_provenance_run_record_unique UNIQUE (
        ingestion_run_id, source_record
    ),
    CONSTRAINT match_provenance_match_run_unique UNIQUE (match_id, ingestion_run_id)
);

CREATE INDEX IF NOT EXISTS matches_season_date_idx
    ON matches (season_id, match_date);
CREATE INDEX IF NOT EXISTS matches_home_team_idx
    ON matches (home_team_id, season_id);
CREATE INDEX IF NOT EXISTS matches_away_team_idx
    ON matches (away_team_id, season_id);
CREATE INDEX IF NOT EXISTS match_provenance_run_idx
    ON match_provenance (ingestion_run_id);

